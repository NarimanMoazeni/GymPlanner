val EnglishStrings: AppStrings = EnglishStringsImpl()

val LocalAppStrings = compositionLocalOf { PersianStrings }

val LocalCurrentLanguage = compositionLocalOf { AppLanguage.PERSIAN }

@Composable
fun FitPlanLocalizationProvider(
    language: AppLanguage,
    content: @Composable () -> Unit
) {
    val strings = if (language == AppLanguage.PERSIAN) PersianStrings else EnglishStrings
    val layoutDirection = if (language == AppLanguage.PERSIAN) {
        androidx.compose.ui.unit.LayoutDirection.Rtl
    } else {
        androidx.compose.ui.unit.LayoutDirection.Ltr
    }

    androidx.compose.runtime.CompositionLocalProvider(
        LocalAppStrings provides strings,
        LocalCurrentLanguage provides language,
        androidx.compose.ui.platform.LocalLayoutDirection provides layoutDirection
    ) {
        content()
    }
}

fun formatDigits(number: Any, language: AppLanguage): String {
    val s = number.toString()
    if (language != AppLanguage.PERSIAN) return s
    val persianDigits = charArrayOf('۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹')
    val builder = StringBuilder()
    for (ch in s) {
        if (ch in '0'..'9') {
            builder.append(persianDigits[ch - '0'])
        } else {
            builder.append(ch)
        }
    }
    return builder.toString()
}
